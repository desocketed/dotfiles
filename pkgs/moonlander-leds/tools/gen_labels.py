#!/usr/bin/env python3
"""Generate src/labels.rs: the key label of every (layer, row, col).

Usage: python3 tools/gen_labels.py QMK_TREE KEYMAP > src/labels.rs
Reads keyboards/zsa/moonlander/keyboard.json
(the LAYOUT key order gives each argument's matrix position) and keymaps/<KEYMAP>/keymap.c.
"""

import json
import re
import sys
from pathlib import Path

LAYERS = ["qwerty", "symbols", "numbers", "media"]
ENUM = {"L_QWRTY": "qwerty", "L_SYMB": "symbols", "L_NUMB": "numbers", "L_MDIA": "media"}
NAMES = {
    "GRV": "`", "TAB": "Tab", "LALT": "Alt", "RALT": "Alt", "LSFT": "Shift", "RSFT": "Shift",
    "LCTL": "Ctrl", "RCTL": "Ctrl", "LGUI": "Gui", "RGUI": "Gui", "SPC": "Space", "BSPC": "Bksp",
    "ENT": "Enter", "ESC": "Esc", "DEL": "Del", "DOWN": "Down", "UP": "Up", "LEFT": "Left",
    "RGHT": "Right", "EQL": "=", "MINS": "-", "BSLS": "\\", "SCLN": ";", "QUOT": "'",
    "COMM": ",", "DOT": ".", "SLSH": "/", "LBRC": "[", "RBRC": "]", "LPRN": "(", "RPRN": ")",
    "LCBR": "{", "RCBR": "}", "PLUS": "+", "PGUP": "PgUp", "PGDN": "PgDn", "PSCR": "PrtSc",
    "MPRV": "Prev", "MPLY": "Play", "MNXT": "Next", "PPLS": "KP+", "PMNS": "KP-",
    "PAST": "KP*", "PSLS": "KP/", "PDOT": "KP.",
}
EXTRA = {
    "RM_NEXT": "RGB next", "RM_TOGG": "RGB", "RM_VALD": "Bright-", "RM_VALU": "Bright+",
    "RM_HUED": "Hue-", "QK_BOOT": "Boot", "MS_BTN1": "Click", "MS_BTN2": "RClick",
    "MS_UP": "Ms Up", "MS_DOWN": "Ms Down", "MS_LEFT": "Ms Left", "MS_RGHT": "Ms Right",
}


def label(code: str) -> str:
    """A short readable label for one keymap entry."""
    if code in ("_______", "KC_TRNS"):
        return "▽"
    if code in ("XXXXXXX", "KC_NO"):
        return ""
    if m := re.fullmatch(r"(?:MO|DF|TG|TO)\((\w+)\)", code):
        return ENUM[m.group(1)]
    if m := re.fullmatch(r"(VOL|BAL)_(\d)", code):
        return f"{m.group(1).title()} {m.group(2)}"
    if code in EXTRA:
        return EXTRA[code]
    if m := re.fullmatch(r"KC_P(\d)", code):
        return f"KP{m.group(1)}"
    if m := re.fullmatch(r"KC_(\w+)", code):
        return NAMES.get(m.group(1), m.group(1))
    return code


def layers(source: str) -> dict[str, list[str]]:
    """The LAYOUT arguments of every layer in keymap.c."""
    found = {}
    for name, body in re.findall(r"\[(L_\w+)\]\s*=\s*LAYOUT\((.*?)\n\s*\)", source, re.S):
        body = re.sub(r"//.*", "", body)
        found[ENUM[name]] = [c.strip() for c in body.split(",") if c.strip()]
    return found


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit("usage: gen_labels.py QMK_TREE KEYMAP")
    tree, name = Path(sys.argv[1]).expanduser(), sys.argv[2]
    board = tree / "keyboards/zsa/moonlander"
    matrix = [k["matrix"] for k in json.loads((board / "keyboard.json").read_text())["layouts"]["LAYOUT"]["layout"]]
    keymap = layers((board / "keymaps" / name / "keymap.c").read_text())
    print("//! The label of every key on every layer, generated by tools/gen_labels.py from the")
    print("//! LAYOUT of each layer in keymaps/<keymap>/keymap.c: (layer, row, col, label).")
    print("//! Transparent keys are ▽, KC_NO is empty.\n")
    print(f"pub const KEY_LABELS: [(&str, u8, u8, &str); {len(LAYERS) * len(matrix)}] = [")
    for layer in LAYERS:
        assert len(keymap[layer]) == len(matrix), layer
        for (row, col), code in zip(matrix, keymap[layer]):
            print(f'    ("{layer}", {row}, {col}, "{label(code).replace(chr(92), chr(92) * 2)}"),')
    print("];")


main()
