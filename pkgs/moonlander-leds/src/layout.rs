/// The finger that presses a key: pinky to index by the column's distance from the outer edge
/// (outer two columns pinky, then ring, middle and three inner columns index), the lowest key
/// of each inner column and the thumb cluster thumb. Assumes the standard Moonlander home
/// position, mirrored for the right half.
pub fn finger(
    row: u8,
    x: f32,
) -> &'static str {
    if row % 6 == 5 {
        return "thumb";
    }
    let reach = if row < 6 { x } else { 16.0 - x };
    match reach.round() as u8 {
        0 | 1 => "pinky",
        2 => "ring",
        3 => "middle",
        _ => "index",
    }
}
